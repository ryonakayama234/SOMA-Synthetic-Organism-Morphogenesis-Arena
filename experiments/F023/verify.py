def _work_charge(vx, vy, jx, jy):
    # Independent integer-ratio construction: all inputs are decimal text.
    u = [Fraction(str(x)) for x in (vx, vy, jx, jy)]
    value = u[0]*u[2] + u[1]*u[3] + (u[2]**2+u[3]**2)/2
    quanta = max(value, Fraction(0))*1000000
    cost = -(-quanta.numerator // quanta.denominator)
    return float(value), cost


def expected_scene(scene):
    """Build expected archive without reading simulator-derived results."""
    action, ledger, physical = [], [], {
        k: scene[k] for k in (
            "world_id","x_a_m","y_a_m","vx_a_mps","vy_a_mps",
            "x_b_m","y_b_m","vx_b_mps","vy_b_mps","mass_a_kg",
            "mass_b_kg","radius_a_m","radius_b_m","restitution",
            "duration_s","sample_dt_s")
    }
    for c in ("a", "b"):
        x, y = scene[f"vx_{c}_mps"], scene[f"vy_{c}_mps"]
        jx,jy = scene[f"command_{c}x_ns"],scene[f"command_{c}y_ns"]
        balance = scene[f"initial_balance_{c}_uj"]
        signed, cost = _work_charge(x,y,jx,jy)
        if jx == 0 and jy == 0:
            reason = "idle"
        elif cost > balance:
            reason = "insufficient_private_budget"
        else:
            reason = "applied"
        gx,gy = (jx,jy) if reason=="applied" else (0.,0.)
        spent = cost if reason=="applied" else 0
        xx,yy = x+gx,y+gy
        physical[f"vx_{c}_mps"] = xx
        physical[f"vy_{c}_mps"] = yy
        action.append(dict(world_id=scene["world_id"],cell_id=c.upper(),time_s=0.,
                           command_x_ns=jx,command_y_ns=jy,
                           applied_x_ns=gx,applied_y_ns=gy,
                           ground_x_ns=-gx,ground_y_ns=-gy,
                           pre_vx_mps=x,pre_vy_mps=y,
                           post_vx_mps=xx,post_vy_mps=yy,
                           candidate_work_j=signed,
                           applied_work_j=signed if reason=="applied" else 0.,
                           candidate_charge_uj=cost,charge_uj=spent,decision=reason))
        ledger.append(dict(world_id=scene["world_id"],cell_id=c.upper(),
                           balance_before_uj=balance,charge_uj=spent,
                           balance_after_uj=balance-spent))
    frames,event = independent_contact_oracle(physical)
    events = [event] if event is not None else []
    original = .5*sum(scene[f"v{axis}_{c}_mps"]**2
                      for c in ("a","b") for axis in ("x","y"))
    end_ke = frames[-1]["total_ke_j"]
    work = sum(a["applied_work_j"] for a in action)
    loss=0.; overlap=0.
    if event:
        n=(event["normal_x"],event["normal_y"])
        dv=(event["pre_vx_b_mps"]-event["pre_vx_a_mps"],
            event["pre_vy_b_mps"]-event["pre_vy_a_mps"])
        g=dv[0]*n[0]+dv[1]*n[1]
        loss=.25*(1.-scene["restitution"]**2)*g*g
        overlap=max(0.,1.-math.hypot(
            event["pre_x_b_m"]-event["pre_x_a_m"],
            event["pre_y_b_m"]-event["pre_y_a_m"]))
    residual=[]
    for axis in ("x","y"):
        last=frames[-1][f"v{axis}_a_mps"]+frames[-1][f"v{axis}_b_mps"]
        before=scene[f"v{axis}_a_mps"]+scene[f"v{axis}_b_mps"]
        ground=sum(r[f"ground_{axis}_ns"] for r in action)
        residual.append(last-before+ground)
    report=dict(world_id=scene["world_id"],contact_count=len(events),
                classification=event["kind"] if event else "none",
                initial_ke_j=original,final_ke_j=end_ke,
                applied_work_j=work,collision_loss_j=loss,
                momentum_residual_kg_mps=max(abs(x) for x in residual),
                energy_residual_j=end_ke-original-work+loss,
                overlap_bound_m=overlap)
    return frames,action,events,ledger,report



def gate_saved_conservation(frozen, states, actions, contacts, audit):
    """Conservation gates on ARCHIVED values, not independent-oracle predictions.

    The independent predicted trajectory is compared separately with same().
    Its relative 1e-9 per-scalar error envelope cannot replace absolute
    conservation of actual saved momentum and energy, especially at Q15
    high speed: a 5e-8 velocity forgery is individually within that envelope
    but violates the conserved total by 5e-8 kg m/s.
    """
    if len(states) != 9*len(frozen) or len(actions) != 2*len(frozen):
        raise AssertionError("saved conservation: cardinality")
    event_by_world = {}
    for event in contacts:
        key = event["world_id"]
        if key in event_by_world:
            raise AssertionError("saved conservation: multiple collisions")
        event_by_world[key] = event
    max_p = max_e = max_overlap = 0.
    if len(audit["world_results"]) != len(frozen):
        raise AssertionError("saved conservation: audit cardinality")
    for idx, scene in enumerate(frozen):
        world = scene["world_id"]
        frames = states[9*idx:9*(idx+1)]
        own_actions = actions[2*idx:2*(idx+1)]
        recorded = audit["world_results"][idx]
        if any(r["world_id"] != world for r in frames+own_actions):
            raise AssertionError(f"{world}: misordered saved evidence")
        if recorded["world_id"] != world:
            raise AssertionError(f"{world}: misordered saved audit")
        event = event_by_world.get(world)
        if event is not None:
            dvx = event["pre_vx_b_mps"]-event["pre_vx_a_mps"]
            dvy = event["pre_vy_b_mps"]-event["pre_vy_a_mps"]
            approach = dvx*event["normal_x"] + dvy*event["normal_y"]
            full_loss = .25*(1.-scene["restitution"]**2)*approach**2
            # Codex P2: an archived collision event is itself physical
            # evidence. Check its actual pre/post velocities, not solely
            # nearby time-grid frames or per-field approximate predictions.
            event_momentum = max(abs(
                event[f"post_v{axis}_a_mps"]+event[f"post_v{axis}_b_mps"]
                -event[f"pre_v{axis}_a_mps"]-event[f"pre_v{axis}_b_mps"])
                for axis in ("x","y"))
            event_pre_ke = .5*sum(event[f"pre_v{axis}_{c}_mps"]**2
                                   for c in ("a","b") for axis in ("x","y"))
            event_post_ke = .5*sum(event[f"post_v{axis}_{c}_mps"]**2
                                    for c in ("a","b") for axis in ("x","y"))
            event_energy = event_post_ke-event_pre_ke+full_loss
            if event_momentum > TOL or abs(event_energy) > TOL:
                raise AssertionError(
                    f"{world}: archived contact conservation broken:"
                    f" momentum={event_momentum}, energy={event_energy}")
            # The per-cell pre/post jump must be the recorded normal
            # impulse. Both disks have immutable unit mass in F023.v1.
            for axis, component in (("x","normal_x"),("y","normal_y")):
                for cell, sign in (("a",-1),("b",1)):
                    actual_jump = (event[f"post_v{axis}_{cell}_mps"]
                                   -event[f"pre_v{axis}_{cell}_mps"])
                    expected_jump = sign*event["impulse_ns"]*event[component]
                    if abs(actual_jump-expected_jump)>TOL:
                        raise AssertionError(
                            f"{world}: archived contact impulse jump broken"
                            f" for {cell}.{axis}")
            overlap = max(0.,1.-math.hypot(
                event["pre_x_b_m"]-event["pre_x_a_m"],
                event["pre_y_b_m"]-event["pre_y_a_m"]))
        else:
            full_loss = overlap = 0.
        before_vx = scene["vx_a_mps"]+scene["vx_b_mps"]
        before_vy = scene["vy_a_mps"]+scene["vy_b_mps"]
        initial_ke = .5*sum(scene[f"v{axis}_{c}_mps"]**2
                            for c in ("a","b") for axis in ("x","y"))
        applied_work = 0.
        for a in own_actions:
            signed,_ = _work_charge(a["pre_vx_mps"],a["pre_vy_mps"],
                                    a["applied_x_ns"],a["applied_y_ns"])
            if abs(signed-a["applied_work_j"]) > TOL:
                raise AssertionError(f"{world}: saved action work inconsistent")
            applied_work += signed
        px_ground = sum(a["ground_x_ns"] for a in own_actions)
        py_ground = sum(a["ground_y_ns"] for a in own_actions)
        # Codex P2: a colliding event can conserve internally while being
        # disconnected from the actual archived trajectory. Anchor the
        # event's incoming state to frozen initial velocities + strictly
        # verified actuator impulses, then anchor its outgoing state to the
        # sampled saved flight after TOI. Both use absolute SI tolerances,
        # never the speed-scaled F022 field comparison.
        post_actuation = {}
        for cell_index, cell in enumerate(("a", "b")):
            for axis in ("x", "y"):
                field = f"v{axis}_{cell}_mps"
                anchor = (scene[field] +
                          own_actions[cell_index][f"applied_{axis}_ns"])
                post_actuation[(cell, axis)] = anchor
                if abs(own_actions[cell_index][f"post_v{axis}_mps"]
                       - anchor) > TOL:
                    raise AssertionError(
                        f"{world}: archived actuation output disconnected")
                if event is not None and abs(
                    event[f"pre_{field}"] - anchor
                ) > TOL:
                    raise AssertionError(
                        f"{world}: archived contact pre-state disconnected"
                        " from frozen actuation")
        if event is not None:
            incoming_ke = .5*sum(v*v for v in post_actuation.values())
            if abs(event_pre_ke-incoming_ke) > TOL:
                raise AssertionError(
                    f"{world}: archived contact pre-energy disconnected")
            first_after = next(
                (row for row in frames
                 if row["time_s"]+1e-12 >= event["time_s"]), None)
            if first_after is None:
                raise AssertionError(
                    f"{world}: contact has no saved post-event sample")
            outgoing_ke = .5*sum(
                first_after[f"v{axis}_{cell}_mps"]**2
                for cell in ("a","b") for axis in ("x","y"))
            if abs(event_post_ke-outgoing_ke) > TOL:
                raise AssertionError(
                    f"{world}: archived contact post-energy disconnected")
            for cell in ("a","b"):
                for axis in ("x","y"):
                    if abs(
                        event[f"post_v{axis}_{cell}_mps"] -
                        first_after[f"v{axis}_{cell}_mps"]
                    ) > TOL:
                        raise AssertionError(
                            f"{world}: archived contact post-state disconnected"
                            " from saved flight")
        final_e = final_p = 0.
        for f in frames:
            kinetic = .5*sum(f[f"v{axis}_{c}_mps"]**2
                             for c in ("a","b") for axis in ("x","y"))
            if abs(f["total_ke_j"]-kinetic) > TOL:
                raise AssertionError(f"{world}: saved frame KE inconsistent")
            px = (f["vx_a_mps"]+f["vx_b_mps"]-before_vx+px_ground)
            py = (f["vy_a_mps"]+f["vy_b_mps"]-before_vy+py_ground)
            p_res = max(abs(px),abs(py))
            loss_so_far = (full_loss if event is not None
                           and f["time_s"]+1e-12 >= event["time_s"] else 0.)
            e_res = kinetic-initial_ke-applied_work+loss_so_far
            if p_res > TOL or abs(e_res) > TOL:
                raise AssertionError(f"{world}: saved physical conservation broken"
                                     f" at sample {f['sample_index']}:"
                                     f" momentum={p_res}, energy={e_res}")
            final_e,final_p = e_res,p_res
        checks = {
            "initial_ke_j":initial_ke,
            "final_ke_j":.5*sum(frames[-1][f"v{axis}_{c}_mps"]**2
                                for c in ("a","b") for axis in ("x","y")),
            "applied_work_j":applied_work,
            "collision_loss_j":full_loss,
            "momentum_residual_kg_mps":final_p,
            "energy_residual_j":final_e,
            "overlap_bound_m":overlap,
        }
        for field,observed in checks.items():
            if abs(recorded[field]-observed)>TOL:
                raise AssertionError(f"{world}: stored audit disagrees with saved {field}")
        if overlap > TOL:
            raise AssertionError(f"{world}: saved collision overlap")
        max_p = max(max_p,final_p)
        max_e = max(max_e,abs(final_e))
        max_overlap = max(max_overlap,overlap)
    for field,observed in (
        ("momentum_residual_kg_mps",max_p),
        ("energy_residual_j",max_e),
        ("overlap_bound_m",max_overlap),
    ):
        if abs(audit[field]-observed)>TOL:
            raise AssertionError(f"saved audit aggregate disagrees: {field}")


def verify(root: Path, *, expected_source_sha=None):
    root=Path(root)
    names = {
        "config_sha256":"scenario.json",
        "states_sha256":"states.jsonl",
        "contacts_sha256":"contacts.jsonl",
        "actions_sha256":"actions.jsonl",
        "ledger_sha256":"ledger.jsonl",
        "audit_sha256":"audit.json",
    }
    manifest=read_one(root/"manifest.json")
    if set(manifest) != {
        "schema_version","frozen_protocol_commit_sha","implementation_commit_sha",
        "python_version","platform",*names,
    } or manifest["schema_version"] != SCHEMA or manifest["frozen_protocol_commit_sha"]!=FREEZE:
        raise AssertionError("manifest/protocol mismatch")
    source = manifest["implementation_commit_sha"]
    if type(source) is not str or len(source)!=40 or any(x not in "0123456789abcdef" for x in source):
        raise AssertionError("bad implementation SHA")
    if expected_source_sha is not None and source != expected_source_sha:
        raise AssertionError("source SHA differs from inspected checkout")
    if type(manifest["python_version"]) is not str or type(manifest["platform"]) is not str:
        raise AssertionError("bad environment")
    for key,file in names.items():
        if manifest[key] != sha(root/file):
            raise AssertionError(f"{file}: SHA mismatch")
    frozen = reference_roster()
    # Frozen configuration is a contract, NOT an inexact simulation result.
    # Example: Q02 .0200000001 instead of .02 costs 201, not 200, microjoules.
    strictly_same(read_one(root/"scenario.json"),
                  {"schema_version":SCHEMA,"worlds":frozen},"preregistered scenario")
    predicted_frames,predicted_actions,predicted_events,predicted_ledgers,checks = [],[],[],[],[]
    for s in frozen:
        f,a,e,l,report=expected_scene(s)
        predicted_frames.extend(f)
        predicted_actions.extend(a)
        predicted_events.extend(e)
        predicted_ledgers.extend(l)
        checks.append(report)
    assert len(frozen)==15 and len(predicted_frames)==135
    assert len(predicted_actions)==len(predicted_ledgers)==30
    saved_states = read_lines(root/"states.jsonl")
    saved_actions = read_lines(root/"actions.jsonl")
    saved_contacts = read_lines(root/"contacts.jsonl")
    saved_ledgers = read_lines(root/"ledger.jsonl")
    check_action_inputs_exact(saved_actions, predicted_actions)
    # Independent predictions still check each derived physical observation.
    same(saved_states, predicted_frames, "world states")
    same(saved_actions, predicted_actions, "private commands")
    same(saved_contacts, predicted_events, "contact events")
    same(saved_ledgers, predicted_ledgers, "private ledger")
    audit=read_one(root/"audit.json")
    expected_audit = dict(schema_version=SCHEMA,world_results=checks,
                          invalid_probe_results={f"J{i:02d}":"rejected" for i in range(1,6)},
                          momentum_residual_kg_mps=max(w["momentum_residual_kg_mps"] for w in checks),
                          energy_residual_j=max(abs(w["energy_residual_j"]) for w in checks),
                          overlap_bound_m=max(w["overlap_bound_m"] for w in checks))
    same(audit,expected_audit,"independent audit")
    # Explicitly gate the ARCHIVED evidence, not just predicted clean worlds.
    gate_saved_conservation(frozen,saved_states,saved_actions,saved_contacts,audit)
    if any(abs(w["energy_residual_j"])>TOL or w["momentum_residual_kg_mps"]>TOL or
           w["overlap_bound_m"]>TOL for w in checks):
        raise AssertionError("physics residual gate")
    # Strong fixed analytic predicates, not merely agreement with a second simulator.
    events={e["world_id"]:e for e in predicted_events}
    if len(predicted_events)!=9 or set(events)!={
        "Q02","Q05","Q06","Q07","Q08","Q09","Q10","Q14","Q15"
    }:
        raise AssertionError("preregistered contact / null classification")
    for k in ("Q02","Q05","Q06","Q07","Q08","Q09","Q10"):
        if not math.isclose(events[k]["time_s"],.9342458972916169,abs_tol=TOL):
            raise AssertionError(f"{k}: first analytic near-miss conversion")
    if not math.isclose(events["Q15"]["time_s"],.095,abs_tol=TOL):
        raise AssertionError("sub-grid high-speed TOI missing")
    if predicted_actions[2]["charge_uj"] != 200 or predicted_actions[6]["charge_uj"] != 0:
        raise AssertionError("private µJ exact boundary")
    return dict(worlds=len(frozen),states=len(predicted_frames),
                contacts=len(predicted_events),actions=len(predicted_actions),
                ledgers=len(predicted_ledgers),invalid_probes=5,
                verified="independent_saved_data_and_rational_energy_oracle")


if __name__=="__main__":
    p=argparse.ArgumentParser()
