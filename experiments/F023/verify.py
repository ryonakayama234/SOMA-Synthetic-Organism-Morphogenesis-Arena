def _work_charge(vx, vy, jx, jy):
    # Independent integer-ratio construction: all inputs are decimal text.
    u = [Fraction(str(x)) for x in (vx, vy, jx, jy)]
    value = u[0]*u[2] + u[1]*u[3] + (u[2]**2+u[3]**2)/2
    quanta = max(value, Fraction(0))*1000000
    cost = -(-quanta.numerator // quanta.denominator)
    return float(value), cost


def expected_scene(scene):
    """Build expected archive without reading simulator-derived results."""
    action, ledger, physical = [], [], {
        k: scene[k] for k in (
            "world_id","x_a_m","y_a_m","vx_a_mps","vy_a_mps",
            "x_b_m","y_b_m","vx_b_mps","vy_b_mps","mass_a_kg",
            "mass_b_kg","radius_a_m","radius_b_m","restitution",
            "duration_s","sample_dt_s")
    }
    for c in ("a", "b"):
        x, y = scene[f"vx_{c}_mps"], scene[f"vy_{c}_mps"]
        jx,jy = scene[f"command_{c}x_ns"],scene[f"command_{c}y_ns"]
        balance = scene[f"initial_balance_{c}_uj"]
        signed, cost = _work_charge(x,y,jx,jy)
        if jx == 0 and jy == 0:
            reason = "idle"
        elif cost > balance:
            reason = "insufficient_private_budget"
        else:
            reason = "applied"
        gx,gy = (jx,jy) if reason=="applied" else (0.,0.)
        spent = cost if reason=="applied" else 0
        xx,yy = x+gx,y+gy
        physical[f"vx_{c}_mps"] = xx
        physical[f"vy_{c}_mps"] = yy
        action.append(dict(world_id=scene["world_id"],cell_id=c.upper(),time_s=0.,
                           command_x_ns=jx,command_y_ns=jy,
                           applied_x_ns=gx,applied_y_ns=gy,
                           ground_x_ns=-gx,ground_y_ns=-gy,
                           pre_vx_mps=x,pre_vy_mps=y,
                           post_vx_mps=xx,post_vy_mps=yy,
                           candidate_work_j=signed,
                           applied_work_j=signed if reason=="applied" else 0.,
                           candidate_charge_uj=cost,charge_uj=spent,decision=reason))
        ledger.append(dict(world_id=scene["world_id"],cell_id=c.upper(),
                           balance_before_uj=balance,charge_uj=spent,
                           balance_after_uj=balance-spent))
    frames,event = independent_contact_oracle(physical)
    events = [event] if event is not None else []
    original = .5*sum(scene[f"v{axis}_{c}_mps"]**2
                      for c in ("a","b") for axis in ("x","y"))
    end_ke = frames[-1]["total_ke_j"]
    work = sum(a["applied_work_j"] for a in action)
    loss=0.; overlap=0.
    if event:
        n=(event["normal_x"],event["normal_y"])
        dv=(event["pre_vx_b_mps"]-event["pre_vx_a_mps"],
            event["pre_vy_b_mps"]-event["pre_vy_a_mps"])
        g=dv[0]*n[0]+dv[1]*n[1]
        loss=.25*(1.-scene["restitution"]**2)*g*g
        overlap=max(0.,1.-math.hypot(
            event["pre_x_b_m"]-event["pre_x_a_m"],
            event["pre_y_b_m"]-event["pre_y_a_m"]))
    residual=[]
    for axis in ("x","y"):
        last=frames[-1][f"v{axis}_a_mps"]+frames[-1][f"v{axis}_b_mps"]
        before=scene[f"v{axis}_a_mps"]+scene[f"v{axis}_b_mps"]
        ground=sum(r[f"ground_{axis}_ns"] for r in action)
        residual.append(last-before+ground)
    report=dict(world_id=scene["world_id"],contact_count=len(events),
                classification=event["kind"] if event else "none",
                initial_ke_j=original,final_ke_j=end_ke,
                applied_work_j=work,collision_loss_j=loss,
                momentum_residual_kg_mps=max(abs(x) for x in residual),
                energy_residual_j=end_ke-original-work+loss,
                overlap_bound_m=overlap)
    return frames,action,events,ledger,report


def verify(root: Path, *, expected_source_sha=None):
    root=Path(root)
    names = {
        "config_sha256":"scenario.json",
        "states_sha256":"states.jsonl",
        "contacts_sha256":"contacts.jsonl",
        "actions_sha256":"actions.jsonl",
        "ledger_sha256":"ledger.jsonl",
        "audit_sha256":"audit.json",
    }
    manifest=read_one(root/"manifest.json")
    if set(manifest) != {
        "schema_version","frozen_protocol_commit_sha","implementation_commit_sha",
        "python_version","platform",*names,
    } or manifest["schema_version"] != SCHEMA or manifest["frozen_protocol_commit_sha"]!=FREEZE:
        raise AssertionError("manifest/protocol mismatch")
    source = manifest["implementation_commit_sha"]
    if type(source) is not str or len(source)!=40 or any(x not in "0123456789abcdef" for x in source):
        raise AssertionError("bad implementation SHA")
    if expected_source_sha is not None and source != expected_source_sha:
        raise AssertionError("source SHA differs from inspected checkout")
    if type(manifest["python_version"]) is not str or type(manifest["platform"]) is not str:
        raise AssertionError("bad environment")
    for key,file in names.items():
        if manifest[key] != sha(root/file):
            raise AssertionError(f"{file}: SHA mismatch")
    frozen = reference_roster()
    same(read_one(root/"scenario.json"),
         {"schema_version":SCHEMA,"worlds":frozen},"preregistered scenario")
    predicted_frames,predicted_actions,predicted_events,predicted_ledgers,checks = [],[],[],[],[]
    for s in frozen:
        f,a,e,l,report=expected_scene(s)
        predicted_frames.extend(f)
        predicted_actions.extend(a)
        predicted_events.extend(e)
        predicted_ledgers.extend(l)
        checks.append(report)
    assert len(frozen)==15 and len(predicted_frames)==135
    assert len(predicted_actions)==len(predicted_ledgers)==30
    same(read_lines(root/"states.jsonl"),predicted_frames,"world states")
    same(read_lines(root/"actions.jsonl"),predicted_actions,"private commands")
    same(read_lines(root/"contacts.jsonl"),predicted_events,"contact events")
    same(read_lines(root/"ledger.jsonl"),predicted_ledgers,"private ledger")
    audit=read_one(root/"audit.json")
    expected_audit = dict(schema_version=SCHEMA,world_results=checks,
                          invalid_probe_results={f"J{i:02d}":"rejected" for i in range(1,6)},
                          momentum_residual_kg_mps=max(w["momentum_residual_kg_mps"] for w in checks),
                          energy_residual_j=max(abs(w["energy_residual_j"]) for w in checks),
                          overlap_bound_m=max(w["overlap_bound_m"] for w in checks))
    same(audit,expected_audit,"independent audit")
    if any(abs(w["energy_residual_j"])>TOL or w["momentum_residual_kg_mps"]>TOL or
           w["overlap_bound_m"]>TOL for w in checks):
        raise AssertionError("physics residual gate")
    # Strong fixed analytic predicates, not merely agreement with a second simulator.
    events={e["world_id"]:e for e in predicted_events}
    if len(predicted_events)!=9 or set(events)!={
        "Q02","Q05","Q06","Q07","Q08","Q09","Q10","Q14","Q15"
    }:
        raise AssertionError("preregistered contact / null classification")
    for k in ("Q02","Q05","Q06","Q07","Q08","Q09","Q10"):
        if not math.isclose(events[k]["time_s"],.9342458972916169,abs_tol=TOL):
            raise AssertionError(f"{k}: first analytic near-miss conversion")
    if not math.isclose(events["Q15"]["time_s"],.095,abs_tol=TOL):
        raise AssertionError("sub-grid high-speed TOI missing")
    if predicted_actions[2]["charge_uj"] != 200 or predicted_actions[6]["charge_uj"] != 0:
        raise AssertionError("private µJ exact boundary")
    return dict(worlds=len(frozen),states=len(predicted_frames),
                contacts=len(predicted_events),actions=len(predicted_actions),
                ledgers=len(predicted_ledgers),invalid_probes=5,
                verified="independent_saved_data_and_rational_energy_oracle")


if __name__=="__main__":
    p=argparse.ArgumentParser()
